const express = require('express')
const router = express.Router()

const brandController = require('../controllers/brandController')
const brandValidation = require('../validations/brandValidation')
const validation = require('../middlewares/validation')

router.post(
    '/create',
    validation(brandValidation.create),
    brandController.create,
)
router.get(
    '/getAll',
    validation(brandValidation.getAll),
    brandController.getAll,
)
router.get(
    '/getById/:brandId',
    validation(brandValidation.getById),
    brandController.getById,
)
router.post(
    '/update/:brandId',
    validation(brandValidation.update),
    brandController.update,
)
router.post(
    '/changeActive/:brandId',
    validation(brandValidation.changeActive),
    brandController.changeActive,
)
router.delete(
    '/delete/:brandId',
    validation(brandValidation.delete),
    brandController.delete,
)
module.exports = router

